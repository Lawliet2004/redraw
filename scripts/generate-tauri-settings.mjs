import fs from "node:fs";
import path from "node:path";
import os from "node:os";

const cargoDir = path.join(os.homedir(), ".cargo", "registry", "src");
function findDir(pattern, sub) {
  for (const registry of fs.readdirSync(cargoDir)) {
    const regPath = path.join(cargoDir, registry);
    if (!fs.statSync(regPath).isDirectory()) continue;
    const matches = fs.readdirSync(regPath)
      .filter((d) => d.startsWith(pattern))
      .sort()
      .reverse();
    for (const match of matches) {
      const full = path.join(regPath, match, sub);
      if (fs.existsSync(full)) return full;
    }
  }
  throw new Error(`Could not find ${pattern}/${sub} in ${cargoDir}`);
}

const tauriDir = findDir("tauri-2.", path.join("mobile", "android"));
const dialogDir = findDir("tauri-plugin-dialog-", "android");
const fsDir = findDir("tauri-plugin-fs-", "android");

const out = `// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
include ":tauri-android"
project(":tauri-android").projectDir = new File("${tauriDir.replace(/\\/g, "/")}")

include ":tauri-plugin-dialog"
project(":tauri-plugin-dialog").projectDir = new File("${dialogDir.replace(/\\/g, "/")}")

include ":tauri-plugin-fs"
project(":tauri-plugin-fs").projectDir = new File("${fsDir.replace(/\\/g, "/")}")
`;

const dest = path.resolve("src-tauri/gen/android/tauri.settings.gradle");
fs.writeFileSync(dest, out, "utf8");
console.log(`Generated ${dest}:\n${out}`);
